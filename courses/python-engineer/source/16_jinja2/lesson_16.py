"""Module 16 — runnable lesson. `python 16_jinja2/lesson_16.py`"""

from __future__ import annotations

from dataclasses import dataclass

from jinja2 import (
    DictLoader,
    Environment,
    StrictUndefined,
    UndefinedError,
    select_autoescape,
)
from jinja2.sandbox import SandboxedEnvironment
from markupsafe import Markup

INTRO = """A template is a fill-in-the-blanks letter. The part that really matters is autoescaping:
if a user names themselves `<script>steal()</script>`, escaping is what stops every
visitor's browser from RUNNING it."""


@dataclass
class Item:
    name: str
    price: float
    active: bool = True


TEMPLATES = {
    "base.html": """<html>
<body>
{% block content %}<p>default content</p>{% endblock %}
</body>
</html>""",
    "page.html": """{% extends "base.html" %}
{% block content %}
{{ super() }}
<h1>{{ title }}</h1>
{% include "list.html" %}
{% endblock %}""",
    "list.html": """<ul>
{% for item in items if item.active %}
<li>{{ loop.index }}. {{ item.name }} — {{ item.price | currency }}</li>
{% else %}
<li>nothing to show</li>
{% endfor %}
</ul>""",
    "macros.html": """{% macro field(name, value="", type="text") -%}
<input name="{{ name }}" value="{{ value }}" type="{{ type }}">
{%- endmacro %}""",
}


def build_env() -> Environment:
    env = Environment(
        loader=DictLoader(TEMPLATES),
        autoescape=select_autoescape(["html", "xml"]),  # security default
        undefined=StrictUndefined,  # typos raise instead of rendering ""
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.filters["currency"] = lambda v: f"${v:,.2f}"
    env.tests["expensive"] = lambda item: item.price > 100
    env.globals["site_name"] = "Python Engineer"
    return env


def basics() -> None:
    print("\n== expressions, filters, control flow ==")
    env = build_env()
    template = env.from_string(
        "{{ name | upper }} has {{ items | length }} item(s), "
        "total {{ items | sum(attribute='price') | currency }}"
    )
    items = [Item("keyboard", 89.99), Item("monitor", 349.0), Item("cable", 9.5, active=False)]
    print(f"  {template.render(name='ada', items=items)}")

    chain = env.from_string(
        "{{ items | selectattr('active') | map(attribute='name') | join(', ') }}"
    )
    print(f"  filter chain: {chain.render(items=items)}")

    custom_test = env.from_string(
        "{% for i in items if i is expensive %}{{ i.name }}{% endfor %}"
    )
    print(f"  custom test: {custom_test.render(items=items)}")


def inheritance_and_includes() -> None:
    print("\n== inheritance, include, loop.else ==")
    env = build_env()
    items = [Item("keyboard", 89.99), Item("monitor", 349.0), Item("cable", 9.5, active=False)]
    rendered = env.get_template("page.html").render(title="Inventory", items=items)
    for line in rendered.splitlines():
        print(f"  {line}")

    empty = env.get_template("list.html").render(items=[])
    print(f"\n  the for/else branch: {empty.strip().splitlines()[1]}")


def macros() -> None:
    print("\n== macros: reusable components ==")
    env = build_env()
    template = env.from_string(
        '{% import "macros.html" as forms %}'
        '{{ forms.field("email", user_email) }}'
        '{{ forms.field("password", type="password") }}'
    )
    print(f"  {template.render(user_email='a@b.c')}")


def autoescaping() -> None:
    print("\n== autoescaping (the security bit) ==")
    env = build_env()
    hostile = '<script>steal()</script>'

    escaped = env.from_string("<p>{{ bio }}</p>").render(bio=hostile)
    print(f"  escaped:  {escaped}")

    unsafe = env.from_string("<p>{{ bio | safe }}</p>").render(bio=hostile)
    print(f"  |safe:    {unsafe}   <- an XSS hole if `bio` is user input")

    trusted = Markup("<em>generated by us</em>")
    print(f"  Markup(): {env.from_string('<p>{{ v }}</p>').render(v=trusted)}")

    off = Environment(autoescape=False).from_string("<p>{{ bio }}</p>").render(bio=hostile)
    print(f"  autoescape OFF: {off}")
    print("  rule: escape by default, and only |safe things YOU built")


def strict_undefined() -> None:
    print("\n== StrictUndefined ==")
    lenient = Environment().from_string("Hello {{ user.naem }}")
    print(f"  default: {lenient.render(user={'name': 'ada'})!r}  <- a typo renders blank")

    strict = build_env().from_string("Hello {{ missing }}")
    try:
        strict.render()
    except UndefinedError as exc:
        print(f"  StrictUndefined: UndefinedError: {exc}")


def streaming_and_sandbox() -> None:
    print("\n== streaming and sandboxing ==")
    env = build_env()
    template = env.from_string("{% for n in numbers %}{{ n }},{% endfor %}")
    stream = template.stream(numbers=range(1_000_000))
    first = next(stream)
    print(f"  stream() yields chunks lazily; first chunk starts with {first[:12]!r}")

    print("\n  a NORMAL environment can be escaped by a hostile template:")
    attack = "{{ ''.__class__.__mro__ }}"
    print(f"    normal env renders: {Environment().from_string(attack).render()[:60]}...")
    try:
        SandboxedEnvironment().from_string(attack).render()
    except Exception as exc:
        print(f"    SandboxedEnvironment: {type(exc).__name__}: {exc}")
    print("  use SandboxedEnvironment whenever USERS supply the template text")


if __name__ == "__main__":
    print(INTRO)
    basics()
    inheritance_and_includes()
    macros()
    autoescaping()
    strict_undefined()
    streaming_and_sandbox()
